// Embeds the MCP Apps in-frame client (App class) into src/panel/app-client.generated.ts so the report needs no CDN.
// Run after upgrading @modelcontextprotocol/ext-apps:  node scripts/embed-app-client.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const pkg = JSON.parse(readFileSync(resolve(root, "node_modules/@modelcontextprotocol/ext-apps/package.json"), "utf8"));
let code = readFileSync(resolve(root, "node_modules/@modelcontextprotocol/ext-apps/dist/src/app-with-deps.js"), "utf8");

// The bundle ends with `export{... X as App}`: drop the export clause and bind App ourselves.
const exportAt = code.lastIndexOf("export{");
const local = /(?:^|[{,])\s*(\w+) as App\b/.exec(code.slice(exportAt))?.[1];
if (exportAt < 0 || !local) throw new Error("could not find the App export in app-with-deps.js");
code = `${code.slice(0, exportAt)}\nvar App = ${local};\n`;
if (code.includes("</script")) throw new Error("bundle contains </script: cannot be inlined safely");

writeFileSync(
  resolve(root, "src/panel/app-client.generated.ts"),
  `// GENERATED by scripts/embed-app-client.mjs from @modelcontextprotocol/ext-apps@${pkg.version}. Do not edit.\nexport const APP_CLIENT_JS = ${JSON.stringify(code)};\n`,
);
console.log(`embedded ext-apps@${pkg.version} client (${Math.round(code.length / 1024)} KB), App = ${local}`);
